describe('the schemas accept what the real server sends', () => {
  it('users list', () => expect(page(userRowSchema).safeParse(users).success).toBe(true));
  it('user detail', () => expect(userDetailSchema.safeParse(detail).success).toBe(true));
  it('audit list', () => expect(page(auditRowSchema).safeParse(audit).success).toBe(true));
  it('payments list', () => expect(page(paymentRowSchema).safeParse(payments).success).toBe(true));
  it('revenue', () => expect(revenueSchema.safeParse(revenue).success).toBe(true));
  it('balances', () => expect(balancesSchema.safeParse(balances).success).toBe(true));
  it('health report', () => expect(healthSchemas.healthSchema.safeParse(c_health).success).toBe(true));
  it('controls: settings, history, deletion requests, trial extension', () => {
    expect(controls.configListSchema.safeParse(c_config).success).toBe(true);
    expect(controls.configHistorySchema.safeParse(c_history).success).toBe(true);
    expect(controls.deletionPageSchema.safeParse(c_deletions).success).toBe(true);
    expect(controls.trialExtensionSchema.safeParse(c_trial).success).toBe(true);
  });
  it('analytics: overview, growth, funnel, active, retention', () => {
    expect(analytics.overviewSchema.safeParse(a_overview).success).toBe(true);
    expect(analytics.growthSchema.safeParse(a_growth).success).toBe(true);
    expect(analytics.funnelSchema.safeParse(a_funnel).success).toBe(true);
    expect(analytics.activeSchema.safeParse(a_active).success).toBe(true);
    expect(analytics.retentionSchema.safeParse(a_retention).success).toBe(true);
  });
  it('analytics: collections, usage, versions, referrals, geography', () => {
    expect(analytics.collectionsPlacesSchema.safeParse(a_collections_state).success).toBe(true);
    expect(analytics.collectionsDaySchema.safeParse(a_collections_day).success).toBe(true);
    expect(analytics.usageSchema.safeParse(a_usage).success).toBe(true);
    expect(analytics.versionsSchema.safeParse(a_versions).success).toBe(true);
    expect(analytics.referralsSchema.safeParse(a_referrals).success).toBe(true);
    expect(analytics.geoSchema.safeParse(a_geo).success).toBe(true);
  });
  it('outreach: groups, preview, announcements, meta, audience count', () => {
    expect(outreach.segmentListSchema.safeParse(o_segments_list).success).toBe(true);
    expect(outreach.segmentSchema.safeParse(o_segment).success).toBe(true);
    expect(outreach.previewSchema.safeParse(o_segment_preview).success).toBe(true);
    expect(outreach.announcementPageSchema.safeParse(o_announcements_list).success).toBe(true);
    expect(outreach.announcementDetailSchema.safeParse(o_announcement_sent).success).toBe(true);
    expect(outreach.announcementDetailSchema.safeParse(o_announcement_detail).success).toBe(true);
    expect(outreach.metaSchema.safeParse(o_announcements_meta).success).toBe(true);
    expect(outreach.audienceCountSchema.safeParse(o_audience_count).success).toBe(true);
  });
});
